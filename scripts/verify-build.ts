/**
 * Automated Production Build Verification Script
 */
import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';

console.log('🏗️ [Build Verification] Running full production build (vite build + esbuild server)...');
const startTime = Date.now();

try {
  execSync('npm run build', { stdio: 'inherit' });
  const duration = ((Date.now() - startTime) / 1000).toFixed(2);
  console.log(`✅ [Build Verification] Build process completed successfully in ${duration}s!`);
} catch (error) {
  console.error('❌ [Build Verification] Build failed!', error);
  process.exit(1);
}

const distDir = path.resolve(process.cwd(), 'dist');
if (!fs.existsSync(distDir)) {
  console.error('❌ [Build Verification] dist/ directory does not exist!');
  process.exit(1);
}

// Check key artifacts
const indexHtml = path.join(distDir, 'index.html');
const serverCjs = path.join(distDir, 'server.cjs');

if (!fs.existsSync(indexHtml)) {
  console.error('❌ [Build Verification] dist/index.html is missing!');
  process.exit(1);
}

const indexStat = fs.statSync(indexHtml);
if (indexStat.size < 500) {
  console.error('❌ [Build Verification] dist/index.html is unexpectedly small (<500B)!');
  process.exit(1);
}

if (!fs.existsSync(serverCjs)) {
  console.error('❌ [Build Verification] dist/server.cjs is missing!');
  process.exit(1);
}

const serverStat = fs.statSync(serverCjs);
if (serverStat.size < 5000) {
  console.error('❌ [Build Verification] dist/server.cjs is unexpectedly small (<5KB)!');
  process.exit(1);
}

console.log(`✅ [Build Verification] dist/index.html (${(indexStat.size / 1024).toFixed(1)} KB) verified.`);
console.log(`✅ [Build Verification] dist/server.cjs (${(serverStat.size / 1024).toFixed(1)} KB) verified.`);

// Verify route directories generated by generateRouteMetatagsPlugin
const sampleRoutes = ['cv', 'all', 'opt', 'portofolio', 'sertifikasi', 'tools'];
let routesVerified = 0;
for (const route of sampleRoutes) {
  const routeIndexPath = path.join(distDir, route, 'index.html');
  if (fs.existsSync(routeIndexPath)) {
    routesVerified++;
  }
}

console.log(`✅ [Build Verification] Verified ${routesVerified}/${sampleRoutes.length} sample pre-rendered meta routes.`);
console.log('🎉 [Build Verification] All production build checks passed!');
